test('Effective dates inclusive; unsupported history and future fail closed', () => {
  assert.equal(sss('10000', { contributionMonth: '2025-01' }).schedule.id, 'SSS-BUSINESS-2025-01');
  assert.equal(calculatePagIbig({ ...context, contributionMonth: '2024-02', monthlyFundSalary: '10000' }).employee.toFixed(2), '200.00');
  for (const month of ['2024-12', '2026-11', '2027-01']) rejects(() => sss('10000', { contributionMonth: month }), 'UNVERIFIED_SCHEDULE');
  rejects(() => calculatePhilHealth({ ...context, contributionMonth: '2024-12', monthlyBasicSalary: '20000' }), 'UNVERIFIED_SCHEDULE');
  rejects(() => calculatePagIbig({ ...context, contributionMonth: '2024-01', monthlyFundSalary: '10000' }), 'UNVERIFIED_SCHEDULE');
  for (const month of ['', '2026-00', '2026-13', '2026-1', '2026-01-15', '0000-01']) rejects(() => sss('10000', { contributionMonth: month }), 'INVALID_MONTH');
});

test('Unresolved coverage and unsupported arrangements/currency fail closed', () => {
  rejects(() => sss('10000', { coverage: undefined as never }), 'UNRESOLVED_COVERAGE');
  rejects(() => sss('10000', { coverage: { status: 'UNKNOWN' } as never }), 'UNRESOLVED_COVERAGE');
  for (const arrangement of ['KASAMBAHAY', 'SELF_EMPLOYED', 'GOVERNMENT', 'PARTIAL_MONTH', 'MULTIPLE_EMPLOYERS', undefined]) {
    rejects(() => sss('10000', { arrangement: arrangement as never }), 'UNSUPPORTED_ARRANGEMENT');
  }
  rejects(() => sss('10000', { currency: 'USD' as never }), 'UNSUPPORTED_CURRENCY');
});

test('Explicit reviewed exemption is distinguishable from a calculated zero', () => {
  for (const calculate of [
    (coverage: ContributionContext['coverage']) => calculateSss({ ...context, coverage, monthlyCompensation: undefined as never }),
    (coverage: ContributionContext['coverage']) => calculatePhilHealth({ ...context, coverage, monthlyBasicSalary: undefined as never }),
    (coverage: ContributionContext['coverage']) => calculatePagIbig({ ...context, coverage, monthlyFundSalary: undefined as never }),
  ]) {
    const coverage = { status: 'EXEMPT' as const, legalBasis: 'Agency-approved exemption', evidenceReference: 'case-123', reviewedBy: 'reviewer-1' };
    const calculated = calculate(coverage);
    assert.equal(calculated.status, 'EXEMPT'); assert.equal(calculated.inputBasis, null);
    assert.deepEqual(calculated.exemption, coverage); assert(calculated.totalRemittance.eq(0));
    for (const key of ['legalBasis', 'evidenceReference', 'reviewedBy'] as const) rejects(() => calculate({ ...coverage, [key]: '' }), 'UNRESOLVED_COVERAGE');
  }
});

test('Missing/invalid/zero monthly bases never become zero contributions', () => {
  for (const calculate of [
    (salary: string) => calculateSss({ ...context, monthlyCompensation: salary }),
    (salary: string) => calculatePhilHealth({ ...context, monthlyBasicSalary: salary }),
    (salary: string) => calculatePagIbig({ ...context, monthlyFundSalary: salary }),
  ]) {
    for (const salary of ['0', '-1', 'NaN', 'Infinity', '1.001', 'abc', '10000000000']) rejects(() => calculate(salary), 'INVALID_BASIS');
    for (const salary of ['', ' ', null, undefined, 10000]) rejects(() => calculate(salary as never), 'UNRESOLVED_BASIS');
  }
  assert(calculateSss({ ...context, monthlyCompensation: decimal('10000') }).employee.eq(500));
});

const scope = { organizationId: 'org-1', employeeId: 'employee-1' };
const first = (monthly: ContributionResult) => allocateContribution(monthly, { ...scope, frequency: 'SEMI_MONTHLY', slot: 'FIRST', priorAllocations: [] });

test('Monthly once; semi-monthly sums to exactly one monthly contribution for every SSS row and odd cent cases', () => {
  for (const monthly of [...officialSssRows.map(([msc]) => sss(msc)), ph('10000.20'), pi('1500.50')]) {
    const before = JSON.stringify(monthly);
    const whole = allocateContribution(monthly, { ...scope, frequency: 'MONTHLY', slot: 'MONTH', priorAllocations: [] });
    const a = first(monthly);
    const b = allocateContribution(monthly, { ...scope, frequency: 'SEMI_MONTHLY', slot: 'SECOND', priorAllocations: [a] });
    for (const share of ['employee', 'employer', 'employerOnly', 'employerTotal', 'totalRemittance'] as const) {
      assert(whole[share].eq(monthly[share])); assert(a[share].add(b[share]).eq(monthly[share]));
    }
    assert.notEqual(a.allocationKey, b.allocationKey);
    assert.equal(JSON.stringify(monthly), before, 'Inputs and prior snapshots remain unchanged');
  }
});

test('Second cutoff reconciles a changed monthly basis; negative corrections require review', () => {
  const a = first(sss('20000'));
  const updated = sss('25000');
  const b = allocateContribution(updated, { ...scope, frequency: 'SEMI_MONTHLY', slot: 'SECOND', priorAllocations: [a] });
  assert(a.employee.add(b.employee).eq(1250));
  assert(b.components[1].employee.eq(250));
  rejects(() => allocateContribution(sss('5000'), { ...scope, frequency: 'SEMI_MONTHLY', slot: 'SECOND', priorAllocations: [a] }), 'INVALID_ALLOCATION');
});

test('Allocation rejects retries, missing ledger, frequency switches and mismatched scope', () => {
  const monthly = sss('20000'), a = first(monthly);
  const request = { ...scope, frequency: 'SEMI_MONTHLY' as const, slot: 'SECOND' as const, priorAllocations: [a] };
  rejects(() => allocateContribution(monthly, { ...request, slot: 'FIRST' }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, priorAllocations: [] }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, priorAllocations: undefined as never }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, frequency: 'MONTHLY', slot: 'MONTH' }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, frequency: 'BIWEEKLY' as never }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, employeeId: 'employee-2' }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, organizationId: 'org-2' }), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(ph('20000'), request), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(sss('20000', { contributionMonth: '2026-09' }), request), 'INVALID_ALLOCATION');
  rejects(() => allocateContribution(monthly, { ...request, priorAllocations: [a, a] }), 'INVALID_ALLOCATION');
  const b = allocateContribution(monthly, request);
  rejects(() => allocateContribution(monthly, { ...request, priorAllocations: [a, b] }), 'INVALID_ALLOCATION');
  const whole = allocateContribution(monthly, { ...scope, frequency: 'MONTHLY', slot: 'MONTH', priorAllocations: [] });
  rejects(() => allocateContribution(monthly, { ...scope, frequency: 'MONTHLY', slot: 'MONTH', priorAllocations: [whole] }), 'INVALID_ALLOCATION');
});

test('Allocation rejects corrupt prior money and component lists', () => {
  const monthly = ph('20000'), a = first(monthly);
  for (const employee of [decimal('-1'), decimal('NaN'), decimal('1.001')]) {
    rejects(() => allocateContribution(monthly, { ...scope, frequency: 'SEMI_MONTHLY', slot: 'SECOND', priorAllocations: [{ ...a, components: [{ ...a.components[0], employee }] }] }), 'INVALID_ALLOCATION');
  }
  rejects(() => allocateContribution(monthly, { ...scope, frequency: 'SEMI_MONTHLY', slot: 'SECOND', priorAllocations: [{ ...a, components: [] }] }), 'INVALID_ALLOCATION');
});

test('Decimal global rounding mode does not change statutory results', () => {
  const mode = Prisma.Decimal.rounding;
  try {
    Prisma.Decimal.set({ rounding: Prisma.Decimal.ROUND_UP });
    amounts(ph('10000.10'), '250', '250.01');
    assert(first(ph('10000.20')).employer.eq(125));
  } finally { Prisma.Decimal.set({ rounding: mode }); }
});
