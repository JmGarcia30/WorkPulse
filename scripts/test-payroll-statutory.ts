const context: ContributionContext = {
  contributionMonth: '2026-10', currency: 'PHP',
  arrangement: 'PRIVATE_EMPLOYEE_SINGLE_EMPLOYER_FULL_MONTH', coverage: { status: 'MANDATORY' },
};
const sss = (salary: string, overrides: Partial<ContributionContext> = {}) => calculateSss({ ...context, ...overrides, monthlyCompensation: salary });
const ph = (salary: string) => calculatePhilHealth({ ...context, monthlyBasicSalary: salary });
const pi = (salary: string) => calculatePagIbig({ ...context, monthlyFundSalary: salary });
const decimal = (value: string) => new Prisma.Decimal(value);
const rejects = (fn: () => unknown, code: string) => assert.throws(fn, (error: unknown) => error instanceof StatutoryContributionError && error.code === code);
function amounts(value: ContributionResult, ee: string, er: string, ec = '0') {
  assert.equal(value.employee.toFixed(2), decimal(ee).toFixed(2));
  assert.equal(value.employer.toFixed(2), decimal(er).toFixed(2));
  assert.equal(value.employerOnly.toFixed(2), decimal(ec).toFixed(2));
  assert(value.employerTotal.eq(decimal(er).add(ec)));
  assert(value.totalRemittance.eq(decimal(ee).add(er).add(ec)));
}

