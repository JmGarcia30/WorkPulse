test('SSS exact EC and MPF transitions; component totals', () => {
  amounts(sss('14749.99'), '725', '1450', '10');
  amounts(sss('14750'), '750', '1500', '30');
  const a = sss('20249.99'), b = sss('20250'), c = sss('34750');
  assert(a.components[1].employee.eq(0));
  assert(b.components[0].employee.eq(1000));
  assert(b.components[1].employee.eq(25));
  assert(b.components[1].employer.eq(50));
  assert(c.components[1].employee.eq(750));
  assert(c.components[1].employer.eq(1500));
  assert(c.totalRemittance.eq(5280));
  for (const share of ['employee', 'employer', 'employerOnly'] as const) {
    assert(c.components.reduce((sum, item) => sum.add(item[share]), decimal('0')).eq(c[share]));
  }
});

