const assert = require('node:assert/strict'), path = require('node:path');
const { randomBytes } = require('node:crypto');
module.exports = async function hostingCompatibility(db, context) {
  const service = require(path.resolve('src/features/company-registration/service.ts'));
  const { proxy } = require(path.resolve('src/proxy.ts'));
  const { NextRequest } = require('next/server');
  const { resolveRequestTenant } = require(path.resolve('src/lib/tenant/server.ts'));
  process.env.PLATFORM_ROOT_DOMAIN = 'work-pulse-omega.vercel.app';
  process.env.PLATFORM_PUBLIC_ORIGIN = 'https://work-pulse-omega.vercel.app';
  const marker = 'b2-host-' + randomBytes(5).toString('hex');
  const proof = randomBytes(32).toString('base64url'), password = randomBytes(24).toString('hex');
  const input = { companyName: marker, administratorName: 'Synthetic HR', email: marker + '@fixture.invalid', password };
  let sent;
  const sender = async message => { sent = message; return { success: true, mode: 'smtp', id: 'synthetic' }; };
  const checks = [];
  const ok = (value, label) => { assert(value, label); checks.push(label); console.log('PASS ' + label); };
  await service.registerCompany(db, input, proof, sender);
  const verified = await service.verifyCompanyRegistration(db, sent.code, randomBytes(32).toString('base64url'), password, input.email);
  const url = new URL(verified.loginUrl);
  ok(url.origin === process.env.PLATFORM_PUBLIC_ORIGIN && url.pathname.startsWith('/w/') && url.pathname.endsWith('/login'), 'B2-H01 Vercel single-host verification produces /w/tenant/login rather than unsupported wildcard subdomain');
  const user = await db.user.findUniqueOrThrow({ where: { email: input.email } });
  ok(user.role === 'HR_ADMIN' && !!user.organizationId, 'B2-H02 cross-device verification initializes the correct HR workspace');
  context.headers = new Headers({ host: url.host });
  const response = await proxy(new NextRequest(url.href, { headers: context.headers }));
  const signed = response.headers.get('x-middleware-request-x-workpulse-routing-context');
  ok(response.status === 200 && !!signed, 'B2-H03 Vercel-style login route receives signed tenant rewrite context');
  context.headers.set('x-workpulse-routing-context', signed);
  ok((await resolveRequestTenant())?.organizationId === user.organizationId, 'B2-H04 rewritten path resolves only the persisted new organization');
  process.env.PLATFORM_PUBLIC_ORIGIN = 'http://work-pulse-omega.vercel.app';
  await assert.rejects(() => service.registerCompany(db, { ...input, email: marker + '-http@fixture.invalid' }, proof, sender), error => error.code === 'SETUP_REQUIRED');
  ok(true, 'B2-H05 non-HTTPS Vercel public origin fails closed');
  process.env.PLATFORM_PUBLIC_ORIGIN = 'https://other.vercel.app';
  await assert.rejects(() => service.registerCompany(db, { ...input, email: marker + '-mismatch@fixture.invalid' }, proof, sender), error => error.code === 'SETUP_REQUIRED');
  ok(true, 'B2-H06 conflicting configured public/root hosts fail closed');
  return { passed: true, assertions: checks.length, checks, productionRequested: false, syntheticOnly: true };
};
