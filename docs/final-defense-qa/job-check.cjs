const assert=require('node:assert/strict');
const {randomBytes}=require('node:crypto');
module.exports=async function(db,context){
  const {hash}=require('bcryptjs');
  const {NextRequest}=require('next/server');
  const {proxy}=require('../../src/proxy.ts');
  const auth=require('../../src/lib/auth/session.ts');
  const actions=require('../../src/features/hiring/actions.ts');
  const marker='qa-jobs-'+randomBytes(5).toString('hex'),passwordHash=await hash(randomBytes(20).toString('hex'),4);
  const org=await db.organization.create({data:{name:'Synthetic job QA',slug:marker,careersEnabled:true}});
  const foreign=await db.organization.create({data:{name:'Synthetic foreign QA',slug:marker+'-foreign'}});
  const user=await db.user.create({data:{name:'Synthetic HR',email:marker+'@fixture.invalid',organizationId:org.id,role:'HR_ADMIN',passwordHash}});
  context.headers=new Headers({host:org.slug+'.localhost:3000'});
  const response=await proxy(new NextRequest('http://'+org.slug+'.localhost:3000/login',{headers:context.headers}));
  const signed=response.headers.get('x-middleware-request-x-workpulse-routing-context');
  if(signed)context.headers.set('x-workpulse-routing-context',signed);
  await auth.createSession({userId:user.id,name:user.name,email:user.email,organizationId:org.id,role:user.role},passwordHash);
  const checks=[];
  const ok=(value,label)=>{assert(value,label);checks.push(label);console.log('PASS '+label);};
  const form=(overrides={})=>{const f=new FormData();for(const [k,v] of Object.entries({title:'Synthetic QA job',department:'Synthetic department',employmentType:'Full-time',location:'Synthetic location',description:'Synthetic description',responsibilities:'Synthetic responsibility',qualifications:'Synthetic qualifications',category:'NON_TEACHING',status:'DRAFT',requirementsJson:JSON.stringify([{name:'Synthetic eligibility',type:'SKILL',isRequired:true}]),...overrides}))f.set(k,v);return f;};
  const redirected=async fn=>{try{await fn();}catch(e){if(e.message.startsWith('REDIRECT:'))return e.message;throw e;}throw Error('EXPECTED_REDIRECT');};
  await redirected(()=>actions.createJobAction(form()));
  let job=await db.job.findFirstOrThrow({where:{organizationId:org.id},include:{structuredReqs:true}});
  ok(job.status==='DRAFT'&&job.structuredReqs.length===1,'REC-004-01 draft creation persists structured requirements');
  await actions.publishJobAction(job.id);job=await db.job.findUniqueOrThrow({where:{id:job.id}});
  ok(job.status==='PUBLISHED'&&!!job.publishedAt,'REC-004-02 publish stamps published state');
  await redirected(()=>actions.updateJobAction(job.id,form({title:'Synthetic QA edited'})));
  ok((await db.job.findUniqueOrThrow({where:{id:job.id}})).title==='Synthetic QA edited','REC-004-03 valid edit saves');
  const foreignJob=await db.job.create({data:{organizationId:foreign.id,title:'Foreign synthetic job',slug:'foreign',department:'QA',employmentType:'Full-time',location:'QA',description:'QA',responsibilities:'QA',qualifications:'QA',requirements:'QA'}});
  ok(!!(await actions.publishJobAction(foreignJob.id)).error,'REC-004-04 cross-tenant publication denied');
  ok((await db.job.findUniqueOrThrow({where:{id:foreignJob.id}})).status==='DRAFT','REC-004-05 foreign job remains unchanged');
  await actions.closeJobAction(job.id);
  ok((await db.job.findUniqueOrThrow({where:{id:job.id}})).status==='CLOSED','REC-004-06 close saves CLOSED state');
  const before=await db.jobRequirement.count({where:{jobId:job.id}});
  let caught;
  try{await actions.updateJobAction(job.id,form({closingDate:'not-a-valid-date'}));}catch(e){caught=e;}
  const after=await db.jobRequirement.count({where:{jobId:job.id}});
  assert(caught,'Invalid date should reject');
  const defect={id:'QA-BUG-004',test:'REC-004-07',status:after===before?'PASS':'FAIL',beforeRequirements:before,afterRequirements:after,errorType:caught.name,expected:'Rejected edit preserves existing requirements',actual:after===before?'Preserved':'Requirements removed before failed job update'};
  console.log(JSON.stringify(defect));require('./qa-runner.cjs').save('job-atomicity',defect);
  if(after!==before)process.exitCode=1;
  return {passed:checks.length===6&&after===before,checks,defect};
};
